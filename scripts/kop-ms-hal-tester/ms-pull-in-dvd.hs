	GETCFG			"NumberOfPulls" TYPE=Controller
	POP				PULL-COUNT
       
	SET				ERROR-STATE	"SUCCESS"
	SET				GRIPPER-MODE	"RENT"
       
       LOC	AT-DRUM-LOC
       POP	DRUM-LOC
       
	IF	TRUE == DRUM-LOC
		LOC
		POP		DECK-LOC
		POP		SLOT-LOC
		LOC	SLOTTYPE	DECK=DECK-LOC	SLOT=SLOT-LOC
		POP	SLOT-TYPE
		IF	"WIDE" == SLOT-TYPE
			SET	GRIPPER-MODE	"OPEN"
		ENDIF
	ENDIF

	TRACK	OPEN
	POP		TRACK-STATUS
	IF	"TIMEOUT" == TRACK-STATUS
		SET	ERROR-STATE "TRACK-OPEN-TIMEOUT"
		JUMP _MACHINE_ERROR
	ENDIF
			
        ROLLER	OUT
        
	DO		PULL-COUNT
		GRIPPER	GRIPPER-MODE
		POP		FINGER-STATUS
		IF	"TIMEOUT" == FINGER-STATUS
			SET ERROR-STATE "GRIPPER FINGER TIMEOUT"
			JUMP	_MACHINE_ERROR
		ENDIF
		
		GRIPPER	EXTEND
		POP		EXTEND-STATUS
		IF	"TIMEOUT" == EXTEND-STATUS
			SET ERROR-STATE "GRIPPER EXTEND TIMEOUT"
			JUMP	_MACHINE_ERROR
		ENDIF
		
		GRIPPER	CLOSE
		POP		FINGER-STATUS
		IF	"TIMEOUT" == FINGER-STATUS
			SET ERROR-STATE "GRIPPER FINGER TIMEOUT"
			JUMP	_MACHINE_ERROR
		ENDIF
		
		GRIPPER	RETRACT
		POP		RETRACT-STATUS
		IF	"TIMEOUT" == RETRACT-STATUS
			SET ERROR-STATE "GRIPPER RETRACT TIMEOUT"
			JUMP	_MACHINE_ERROR
		ENDIF
	LOOP

	GRIPPER OPEN
	POP	FINGER-STATUS

	TRACK	CLOSE	
	POP	TRACK-STATUS
	IF	"TIMEOUT" == TRACK-STATUS
		SET	ERROR-STATE "TRACK CLOSE TIMEOUT"
		JUMP	_MACHINE_ERROR
	ENDIF
	
	ROLLER	POS=4 WAIT=TRUE TIMEOUT=3000
	POP		ROLLER-POS-TIMEOUT
	IF		"TIMEOUT" == ROLLER-POS-TIMEOUT
			SET	ERROR-STATE "ROLLER POS4 TIMEOUT"
			JUMP	_MACHINE_ERROR
	ENDIF
	
	JUMP _DONE
		        
_MACHINE_ERROR:
	LOG				"There was an error while pushing in the DVD: {0}" ERROR-STATE ENTRYTYPE=ERROR

_DONE:
	TRACK	CLOSE
        POP		TRACK-CLOSE-STATUS
	
        ROLLER	STOP
        GRIPPER	RETRACT
        POP		GRIPPER-RETRACT-STATUS
	PUSHB		ERROR-STATE 
	NOP
		