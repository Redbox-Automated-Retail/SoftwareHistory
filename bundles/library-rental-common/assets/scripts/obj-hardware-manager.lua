get_vmz_thin_barcodes = function()
	local sort_order = {
		["DNR"] = 1,
		["DAMAGED"] = 2,
		["FRAUD"] = 3,
		["DEFAULT"] = 4
	}

	local barcodes_to_bin = {}
	local rebalances = {}
	local redeployments = {}
	local barcodes_to_vmz = {}

	local barcode_in_exclude_list = function( barcode )
		if barcode == nil then
			return false
		end
		for _,v in ipairs( exclude_barcodes or {} ) do
			if v["Barcode"] == barcode then
				return true
			end
		end
		return false
	end

	for k, v in BarcodePosition:pairs() do
		local barcode = v["barcode"]
		local status = v["status"]
		if barcode ~= nil
		and status ~= nil
		and barcode ~= "UNDEFINED"
		and barcode ~= "EMPTY" then
			local row = {}
			row.barcode = barcode
			row.status = status

			local do_not_rent_date = nil
			if BarcodeToProduct[barcode] ~= nil and BarcodeToProduct[barcode].product_id ~= nil then
				local product_id = BarcodeToProduct[barcode].product_id
				if MasterProductCatalog[product_id] ~= nil and MasterProductCatalog[product_id].do_not_rent_date ~= nil then
					do_not_rent_date = MasterProductCatalog[product_id].do_not_rent_date
				end
			end
            row.status = get_rapid_status( barcode, row.status )			
			if string.upper( row.status ) == "DAMAGED" then
				row.order = sort_order["DAMAGED"]
				table.insert( barcodes_to_bin, row )
				kernel.log(">  added Damaged (sort_order:" ..sort_order["DAMAGED"] ..") " .. barcode .." to barcodes_to_bin from location " .. k )
			elseif string.upper( row.status ) == "FRAUD" then
				row.order = sort_order["FRAUD"]
                if EnableDiscSecurity == true then
                    kernel.log(">  DiscSecurityEnabled fraud disc barcode: " .. barcode .." will not be thinned." )
                else
				    table.insert( barcodes_to_bin, row )
				    kernel.log(">  added Fraud (sort_order:" ..sort_order["FRAUD"] ..") " .. barcode .." to barcodes_to_bin from location " .. k )
                end
			elseif do_not_rent_date ~= nil and do_not_rent_date <= get_current_date_string( "%4d%02d%02d%02d%02d" ) then
				row.order = sort_order["DNR"]
				table.insert( barcodes_to_bin, row )
				kernel.log(">  added DNR (sort_order:" ..sort_order["DNR"] ..") " .. barcode .." to barcodes_to_bin from location " .. k )
			elseif string.upper( row.status ) == "THINNED" then
				row.order = sort_order["DEFAULT"]
				table.insert( barcodes_to_vmz, row )
				kernel.log(">  added Thinned (sort_order:" ..sort_order["DEFAULT"] ..") " .. barcode .." to barcodes_to_vmz from location " .. k )
			end
		end
	end

	table.sort(
		barcodes_to_bin,
		function( a, b )
			if b ~= nil and b ~= nil then
		--[[***	Fix for Defect #5836
				Changing the order in which we are sorting the list of barcodes for the job since the HAL job stack processes the barcode list in the reverse order.]]
				return a.order > b.order
			end
			return false
		end
	)
--[[
	-- Get redeployment barcodes
	local rebalance = kernel.rental_inventory_get_rapidstatus_by_status("Rebalancing") or {}

	for k, v in pairs(rebalance) do
		if k ~= nil then
			local row = {}
			row.barcode = v["barcode"]
			table.insert( rebalances, row)
			kernel.log(">  added Rebalancing " .. row.barcode .." to rebalances" )
		end
	end

	-- Get redeployment barcodes
	local redeploy = kernel.rental_inventory_get_rapidstatus_by_status("Redeployment") or {}
	for k, v in pairs(redeploy) do
		if k ~= nil then
			local row = {}
			row.barcode = v["barcode"]
			table.insert( redeployments, row)
			kernel.log(">  added Redeployment " .. row.barcode .." to redeployments" )
		end
	end
	--]]
	local rebalance = kernel.rental_inventory_get_barcodes_by_status("Rebalancing", true) or {}
	for k, v in pairs(rebalance) do
		if k ~= nil then
			local row = {}
			row.barcode = v --v["barcode"]
			table.insert( rebalances, row)
			kernel.log(">  added Rebalancing " .. row.barcode .." to rebalances" )
		end
	end	
	
	local redeploy = kernel.rental_inventory_get_barcodes_by_status("Redeployment", true) or {}
	for k, v in pairs(redeploy) do
		if k ~= nil then
			local row = {}
			row.barcode = v --v["barcode"]
			table.insert( redeployments, row)
			kernel.log(">  added Redeployment " .. row.barcode .." to redeployments" )
		end
	end	

	return barcodes_to_bin, rebalances, redeployments, barcodes_to_vmz
end

local is_release_date_less_than_28_days = function( release_date )
	local current = os.date( "*t" )
	local four_weeks_out = kernel.dateadd( current, "28" )
	local four_weeks_out_string = string.format( "%4d%02d%02d%02d%02d", four_weeks_out.year, four_weeks_out.month, four_weeks_out.day, four_weeks_out.hour, four_weeks_out.min )
	return release_date < four_weeks_out_string
end

function newhardwaremanager()
	local t = {}

	t.hardware_event_responders = {}

	t.reset_event_responders = function( self )
		self.hardware_event_responders = {}
	end

	t.default_status_change_handler = function( jobid, timestamp, message )
		if VerboseLogging then kernel.log("hardwaremanager default_status_change_handler BEGIN") end
		kernel.log("Message : ".. message)
		local i, _ = string.find( message, ">STATUS CHANGE<" )
		if i == nil then
			kernel.log("Running hardware_process_event")
			t:hardware_process_event( jobid, message )
		end
		if VerboseLogging then kernel.log("hardwaremanager default_status_change_handler COMPLETE") end
	end

	t.init = function( self, on_complete )
		local result =  kernel.hardwareinint(
			self.default_status_change_handler,
			function( jobid, status )
				if has_job_ended( status ) then
					local job_result = kernel.hardwaregetprogramresults( jobid )
					enqueue_inventory_updates( job_result )
					if on_complete ~= nil then
						on_complete( job_result )
					end
					kernel.hardwaretrashjob( jobid )
				end
			end )
		if result.success == false then
			self:show_hardware_errors( result )
			return false
		end
		return true
	end

	t.check_picker = function( self, on_complete )
		local result =  kernel.hardwarecheckpicker(
			self.default_status_change_handler,
			function( jobid, status )
