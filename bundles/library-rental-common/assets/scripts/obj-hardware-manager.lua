	t.clean_inventory = function( self )
		-- Clean orphaned reservations prior to other updates so that all tables will update cleanly
		if ReservationManager ~= nil then
			ReservationManager:remove_orphaned_reservations()
		end

		kernel.log( "Clean Inventory BEGIN" )
		kernel.log( "> build list of present barcodes" )
		local present_barcodes = {}
		for k, v in BarcodePosition:pairs() do
			if v.barcode ~= nil
			and v.barcode ~= "UNKNOWN"
			and v.barcode ~= "EMPTY"
			then
				present_barcodes[ v.barcode ] = true
			end
		end
		kernel.log( "> compare cached product barcodes to present barcodes" )
		for _, v in ProductCatalog:pairs() do
			local history = ProductHistory[ v.product_id ]
			local product = MasterProductCatalog[ v.product_id ]

			if ( v.in_stock ~= nil and v.in_stock == true) or (history ~= nil and history.on_hand_count > 0 ) then
				local on_hand_count = 0
				local barcodes_table = ProductToBarcode[v.product_id] or {}
				local barcodes_to_delete = {}

				for each_barcode, cached_info in pairs( barcodes_table ) do
					local corp_inv_record = BarcodeToProduct[ each_barcode ]
					if corp_inv_record == nil
					or corp_inv_record.product_id ~= v.product_id
					then
						local log_title_id = "Missing"
						if corp_inv_record ~= nil and corp_inv_record.product_id ~= nil then
							log_title_id = corp_inv_record.product_id
						end
						-- If barcode was remapped to a different product by corporate, remove it from this product
						kernel.log( "> barcode: " .. tostring( each_barcode ) .. " title ID change detected. OLD:" ..
							v.product_id .. ", NEW:" .. log_title_id )
						barcodes_to_delete[ each_barcode ] = true
					else
						if cached_info ~= nil then
							if ( cached_info.status == "Known"
							or cached_info.status == "Thinned"
							or cached_info.status == "Redeployment"
							or cached_info.status == "Rebalancing" )
							and present_barcodes[ each_barcode ] ~= nil
							then
								on_hand_count = on_hand_count + 1
							end
						end
					end
				end

				-- Remove mismapped barcodes from this product
				for barcode_k, barcode_v in pairs( barcodes_to_delete ) do
					kernel.log( "> barcode: " .. tostring( barcode_k ) .. " removed from title " .. v.product_id )
					barcodes_table[ barcode_k ] = nil
				end
				ProductToBarcode[v.product_id] = barcodes_table --forces commit

				if on_hand_count == 0 then
					kernel.log(">> False Positive in_stock OR on_hand_count cleared for Product " .. v.product_id )
					v.in_stock = false
					history.on_hand_count = 0
					if product ~= nil and is_release_date_less_than_28_days( product.merchandise_date ) == false then
						ProductHistory:remove( v.product_id )
						ProductCatalog:remove( v.product_id )
					else
						ProductHistory[v.product_id] = history --forces commit
						ProductCatalog[v.product_id] = v --forces commit
					end
				end
			elseif history ~= nil then
				if product == nil or ( history.on_hand_count == 0 and is_release_date_less_than_28_days( product.merchandise_date ) == false ) then
					ProductHistory:remove( v.product_id )
					ProductCatalog:remove( v.product_id )
				else
					-- Added to clean up coming soon titles which never arrive and whose release date has passed
					create_or_update_product_catalog_entry( v.product_id, history )
				end
			end
		end
		kernel.log("Clean Inventory END")

		kernel.log("Clean DupSyncHistory BEGIN")
		local discs_to_expire = {}
		for k, v in DuplicateSlotFixes:pairs() do
			local current_date = get_current_date_string( "%4d%02d%02d%02d%02d" )
			local days_elapsed = kernel.getelapseddays( v.last_update, current_date )
			if days_elapsed > 7 then
				discs_to_expire[ k ] = true
			end
		end
		for k, v in pairs( discs_to_expire ) do
			DuplicateSlotFixes:remove( k )
			kernel.log( "> expired duplicate sync record for barcode: " .. tostring( k ) )
		end
		kernel.log("Clean DupSyncHistory END")
	end

