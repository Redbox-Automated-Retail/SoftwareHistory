	t.hardware_process_event = function( self, jobid, event )
		if VerboseLogging then kernel.log("hardwaremanager hardware_process_event BEGIN") end
		if VerboseLogging then kernel.log("Event received by hardware_process_event:".. event) end
		local args = nil
		local i = string.find( event, ":" )
		if i ~= nil then
			args = string.split( string.sub( event, i + 1 ), "," )
			event = string.sub( event, 1, i - 1 )
		end
		kernel.log(self.hardware_event_responders[event])
		local responder = self.hardware_event_responders[event]
		if responder == nil then
			kernel.log(">> responder was nil for " .. event )
			return
		end
		kernel.log(">> responder executing for " .. event )
		responder( args, jobid )
		if VerboseLogging then kernel.log(">> responder completed" ) end
		if VerboseLogging then kernel.log("hardwaremanager hardware_process_event COMPLETE") end
	end

