				for k, v in ipairs( kiosk_engine_jobs ) do
					if length( v ) >= length( p)
					and string.sub( v, 1, length( p ) ) == p then
						kiosk_engine_jobs[ k ] = nil --Clear job, it will be reloaded below
					end
				end
			end
		end

		local result_kioskengine = scheduler_services.get_entries()
		local index = 1

		for _, p in ipairs( program ) do
			for _, v in ipairs( result.results ) do
				if v.program == p then
					local excluded_status = false

					if exclude_status ~= nil then
