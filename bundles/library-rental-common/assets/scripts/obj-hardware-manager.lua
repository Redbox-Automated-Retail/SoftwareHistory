					end
				end
			end

			if result_kioskengine ~= nil then
				for _, v in ipairs( result_kioskengine ) do
					if v.program == p then
						local quartz_job_name = v.id
						v.id = "KE-" .. tostring( index )
						kiosk_engine_jobs[ v.id ] = quartz_job_name
						kernel.log( "Found scheduler job " .. quartz_job_name .. ", assigned locally to " .. v.id )
						local jobtime = newdatetime()
						jobtime:set_from_cron_expression( tostring( v.starttime ) )
						v.starttime = tostring( jobtime )

						local excluded_status = false

						if exclude_status ~= nil then
							table.foreach(
								exclude_status,
								function(key, value)
									if v.status == value then
										excluded_status = true
									end
								end)
						end

						if not excluded_status then
							table.insert( jobs, v )
							index = index + 1
						end
					end
				end
			end
		end

		return jobs
	end

